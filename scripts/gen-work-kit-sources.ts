#!/usr/bin/env bun
/**
 * Which work-kit files Tailwind reads for the renderer's stylesheet
 * (docs/agents/work-kit.md "Tailwind"). Tailwind skips node_modules, so the
 * classes of a work-kit component reach the stylesheet only through an
 * `@source` line. Naming the whole package put every primitive's classes
 * in the first paint, used or not (89 KB on 2026-11-19, with nothing of it
 * on screen), so the lines name only the files the renderer imports: each
 * `work-kit/…` specifier under src/renderer/src, and every work-kit file
 * those reach. The probe is always listed: its class proves the lines work.
 *
 * A thread that starts importing a work-kit module runs this and commits
 * the file; scripts/workKitPin.test.ts fails until it does.
 *
 *   bun scripts/gen-work-kit-sources.ts           # write src/renderer/src/work-kit-sources.css
 *   bun scripts/gen-work-kit-sources.ts --check   # exit 1 when the file is out of step
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { keptImports } from './entry-graph'

export const SOURCES_FILE = 'src/renderer/src/work-kit-sources.css'
const KIT = 'node_modules/work-kit'
/** Always read: `KitProbe`'s class is how a host proves its Tailwind reads the package. */
const PROBE = `${KIT}/src/ui/kit-probe.tsx`

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return sourceFiles(path)
    return /\.(ts|tsx)$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : []
  })
}

/** The file a `work-kit/<sub>` specifier names, through the package's own export map. */
export function kitFile(root: string, specifier: string): string | null {
  const sub = `./${specifier.slice('work-kit/'.length)}`
  const exports = (JSON.parse(readFileSync(resolve(root, KIT, 'package.json'), 'utf8')) as { exports: Record<string, string> }).exports
  let target = exports[sub]
  if (!target) {
    // A pattern (`./ui/*`): the longest prefix wins, as node resolves it.
    const [pattern] = Object.keys(exports)
      .filter((key) => key.includes('*') && sub.startsWith(key.slice(0, key.indexOf('*'))) && sub.endsWith(key.slice(key.indexOf('*') + 1)))
      .sort((a, b) => b.indexOf('*') - a.indexOf('*'))
    if (!pattern) return null
    const star = sub.slice(pattern.indexOf('*'), sub.length - (pattern.length - pattern.indexOf('*') - 1))
    target = exports[pattern].replace('*', star)
  }
  const file = join(KIT, target)
  return existsSync(resolve(root, file)) ? file : null
}

const candidates = (base: string): string[] => [base, `${base}.ts`, `${base}.tsx`, join(base, 'index.ts'), join(base, 'index.tsx')]

/** The `work-kit/…` specifiers the renderer's own files name, in any import. */
export function rendererSpecifiers(root = resolve('.')): string[] {
  const found = new Set<string>()
  for (const file of sourceFiles(resolve(root, 'src/renderer/src')))
    for (const [, spec] of readFileSync(file, 'utf8').matchAll(/["'`](work-kit\/[^"'`\s]+)["'`]/g)) found.add(spec)
  return [...found].sort()
}

/** Every work-kit source file these specifiers reach, the probe first. */
export function kitSources(root = resolve('.'), specifiers: readonly string[] = rendererSpecifiers(root)): string[] {
  const reached = new Set<string>([PROBE])
  const queue: string[] = []
  const reach = (file: string | null): void => {
    if (!file || reached.has(file)) return
    reached.add(file)
    queue.push(file)
  }
  for (const spec of specifiers) reach(kitFile(root, spec))
  for (let file = queue.shift(); file; file = queue.shift()) {
    if (!/\.(ts|tsx)$/.test(file)) continue
    const text = readFileSync(resolve(root, file), 'utf8')
    // What the build keeps, and what a dynamic import asks for later: both draw on screen.
    const specs = [...keptImports(file, text), ...[...text.matchAll(/\bimport\(\s*["'`]([^"'`]+)["'`]\s*\)/g)].map((m) => m[1])]
    for (const spec of specs) {
      if (spec.startsWith('work-kit/')) reach(kitFile(root, spec))
      else if (spec.startsWith('.')) reach(candidates(join(dirname(file), spec)).find((path) => /\.(ts|tsx)$/.test(path) && existsSync(resolve(root, path))) ?? null)
    }
  }
  return [PROBE, ...[...reached].filter((file) => file !== PROBE && /\.(ts|tsx)$/.test(file)).sort()]
}

/** The stylesheet's text for these files. */
export function sourcesCss(files: readonly string[], root = resolve('.')): string {
  const from = dirname(resolve(root, SOURCES_FILE))
  return [
    '/* Generated by scripts/gen-work-kit-sources.ts; never edit. The work-kit files Tailwind reads for the renderer:',
    '   the ones src/renderer/src imports and what they reach, and the probe. `bun scripts/gen-work-kit-sources.ts` writes it. */',
    ...files.map((file) => `@source "${relative(from, resolve(root, file))}";`),
    ''
  ].join('\n')
}

if (import.meta.main) {
  const text = sourcesCss(kitSources())
  if (process.argv.includes('--check')) {
    if (!existsSync(SOURCES_FILE) || readFileSync(SOURCES_FILE, 'utf8') !== text) {
      console.error(`${SOURCES_FILE} is out of step: run bun scripts/gen-work-kit-sources.ts`)
      process.exit(1)
    }
  } else {
    writeFileSync(SOURCES_FILE, text)
    console.log(`${SOURCES_FILE}: ${kitSources().length} file(s)`)
  }
}
