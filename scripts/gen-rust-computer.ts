interface JS {
  $ref?: string
  type?: string
  properties?: Record<string, JS>
  required?: string[]
  items?: JS
  enum?: string[]
  const?: unknown
  anyOf?: JS[]
  oneOf?: JS[]
  additionalProperties?: JS | boolean
}

const HEADER = [
  '// Generated by scripts/gen-rust-computer.ts from src/shared/computer/ — do not edit.',
  '// Regenerate with `bun scripts/gen-rust-computer.ts`; scripts/gen-rust-computer.test.ts fails when this is stale.',
  ''
]

const KEYWORDS = new Set(
  'as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try'.split(' ')
)

const refName = (ref: string): string => ref.slice(ref.lastIndexOf('/') + 1)

/** `bundleId` → `bundle_id`, `start_element` stays, a keyword gets `r#`. */
function snake(name: string): string {
  const s = name
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase()
    .replace(/^_+|_+$/g, '')
  const id = /^[0-9]/.test(s) ? `n${s}` : s
  return KEYWORDS.has(id) ? `r#${id}` : id
}

/** A wire name as a Rust type or variant name: `state.get` → `StateGet`, `$/cancel` → `Cancel`. */
const typeName = (name: string): string => pascal(name.replace(/^\$\//, '').replace(/^__(params|output):/, '')) || 'Empty'

const enumKey = (values: readonly string[]): string => JSON.stringify([...values].sort())

interface Emitter {
  defs: Record<string, JS>
  /** a named string enum by its sorted values, so an inline copy reuses it */
  enums: Map<string, string>
  /** the union branches and the field each is tagged by */
  branchTag: Map<string, string>
  out: string[][]
  declared: Set<string>
}

/** The Rust type of a schema; declares inline objects and enums under `hint`. */
function rustType(em: Emitter, schema: JS, hint: string): string {
  if (schema.$ref) return typeName(refName(schema.$ref))
  if (schema.anyOf) {
    const rest = schema.anyOf.filter((s) => s.type !== 'null')
    if (rest.length === 1 && rest.length < schema.anyOf.length) return rustType(em, rest[0], hint)
    return 'serde_json::Value'
  }
  if (schema.enum) {
    const named = em.enums.get(enumKey(schema.enum))
    if (named) return named
    declareEnum(em, hint, schema.enum)
    return hint
  }
  switch (schema.type) {
    case 'string':
      return 'String'
    case 'integer':
      return 'i64'
    case 'number':
      return 'f64'
    case 'boolean':
      return 'bool'
    case 'array':
      return `Vec<${schema.items ? rustType(em, schema.items, `${hint}Item`) : 'serde_json::Value'}>`
    case 'object':
      if (!schema.properties && schema.additionalProperties && typeof schema.additionalProperties === 'object')
        return `std::collections::BTreeMap<String, ${rustType(em, schema.additionalProperties, `${hint}Value`)}>`
      if (!schema.properties) return 'serde_json::Value'
      declareStruct(em, hint, schema)
      return hint
  }
  return 'serde_json::Value'
}

const nullable = (schema: JS): boolean => !!schema.anyOf?.some((s) => s.type === 'null')

function declareStruct(em: Emitter, name: string, schema: JS, skip?: string): void {
  if (em.declared.has(name)) return
  em.declared.add(name)
  const required = new Set(schema.required ?? [])
  const lines = ['#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]', `pub struct ${name} {`]
  for (const [key, prop] of Object.entries(schema.properties ?? {})) {
    if (key === skip) continue
    let ty = rustType(em, prop, name + pascal(key))
    const optional = !required.has(key)
    const attrs: string[] = []
    const field = snake(key)
    if (field.replace(/^r#/, '') !== key) attrs.push(`rename = ${JSON.stringify(key)}`)
    if (optional) {
      ty = `Option<${ty}>`
      attrs.push('default', 'skip_serializing_if = "Option::is_none"')
    } else if (nullable(prop)) {
      ty = `Option<${ty}>`
      attrs.push('default')
    }
    if (attrs.length) lines.push(`    #[serde(${attrs.join(', ')})]`)
    lines.push(`    pub ${field}: ${ty},`)
  }
  lines.push('}')
  em.out.push(lines)
}

function declareEnum(em: Emitter, name: string, values: readonly string[]): void {
  if (em.declared.has(name)) return
  em.declared.add(name)
  const variant = (v: string): string => pascal(v) || 'Empty'
  const lines = [
    '#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]',
    `pub enum ${name} {`,
    ...values.flatMap((v) => [`    #[serde(rename = ${JSON.stringify(v)})]`, `    ${variant(v)},`]),
    '    /// a value this build does not know (a newer host); never sent',
    '    #[serde(other)]',
    '    #[default]',
    '    Unrecognized,',
    '}',
    '',
    `impl ${name} {`,
    '    /// The wire word.',
    '    pub fn as_str(&self) -> &\'static str {',
    '        match self {',
    ...values.map((v) => `            ${name}::${variant(v)} => ${JSON.stringify(v)},`),
    `            ${name}::Unrecognized => "unrecognized",`,
    '        }',
    '    }',
    '}'
  ]
  em.out.push(lines)
}

function declareUnion(em: Emitter, name: string, schema: JS, tag: string): void {
  em.declared.add(name)
  const lines = ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', `#[serde(tag = ${JSON.stringify(tag)})]`, `pub enum ${name} {`]
  for (const branch of schema.oneOf ?? []) {
    const id = refName(branch.$ref!)
    const def = em.defs[id]
    const value = String(def.properties![tag].const)
    declareStruct(em, typeName(id), def, tag)
    lines.push(`    #[serde(rename = ${JSON.stringify(value)})]`, `    ${pascal(value) || 'Empty'}(${typeName(id)}),`)
  }
  const first = (em.defs[refName(schema.oneOf![0].$ref!)].properties![tag].const as string)
  lines.push('}', '', `impl Default for ${name} {`, `    fn default() -> Self {`, `        ${name}::${pascal(first) || 'Empty'}(Default::default())`, '    }', '}')
  em.out.push(lines)
}

/** The wire types: every named type, each union, and each method's params and result. */
export function emitWire(): string {
  const { defs, methods } = jsonSchemas(COMPUTER_SUBSET, COMPUTER_METHOD_SOURCE)
  const em: Emitter = { defs, enums: new Map(), branchTag: new Map(), out: [], declared: new Set() }
  for (const entry of COMPUTER_SUBSET)
    if (entry.kind === 'type' && defs[entry.id]?.enum) em.enums.set(enumKey(defs[entry.id].enum!), typeName(entry.id))
  for (const entry of COMPUTER_SUBSET) {
    if (entry.kind === 'type') {
      const def = defs[entry.id]
      if (def.enum) declareEnum(em, typeName(entry.id), def.enum)
      else if (def.type === 'object' && def.properties) declareStruct(em, typeName(entry.id), def)
      else if (def.type === 'object') {
        em.declared.add(entry.id)
        em.out.push([`pub type ${typeName(entry.id)} = serde_json::Map<String, serde_json::Value>;`])
      } else em.out.push([`pub type ${typeName(entry.id)} = ${rustType(em, def, typeName(entry.id))};`])
    } else if (entry.kind === 'union') declareUnion(em, typeName(entry.id), defs[entry.id], entry.discriminator)
  }
  const methodLines = ['/// Every method of COMPUTER_METHODS: its wire name, `Params` and `Result`.', 'pub mod methods {']
  const methodTypes: [string, string, string][] = []
  for (const m of methods) {
    const base = typeName(m.method)
    const params = m.paramsId ? (m.paramsId.startsWith('__') ? namedInline(em, `${base}Params`, defs[m.paramsId]) : typeName(m.paramsId)) : 'Empty'
    const result = m.outputId.startsWith('__') ? namedInline(em, `${base}Result`, defs[m.outputId]) : typeName(m.outputId)
    methodTypes.push([base, params, result])
  }
  const sup = (t: string): string => (/^[A-Z]\w*$/.test(t) ? `super::${t}` : t)
  for (const [base, params, result] of methodTypes)
    methodLines.push(`    pub type ${base}Params = ${sup(params)};`, `    pub type ${base}Result = ${sup(result)};`)
  methodLines.push(`    /// The wire names, in COMPUTER_METHODS' order.`, `    pub const NAMES: &[&str] = &[${methods.map((m) => JSON.stringify(m.method)).join(', ')}];`, '}')
  return [
    ...HEADER,
    '#![allow(dead_code, clippy::all)]',
    'use serde::{Deserialize, Serialize};',
    '',
    ...em.out.flatMap((l) => [...l, '']),
    ...methodLines,
    ''
  ].join('\n')
}

function namedInline(em: Emitter, name: string, schema: JS): string {
  if (schema.type === 'object' && schema.properties && Object.keys(schema.properties).length === 0) return 'Empty'
  return rustType(em, schema, name)
}

const rustStr = (s: string): string => JSON.stringify(s)
const strList = (xs: Iterable<string>): string => `&[${[...xs].map(rustStr).join(', ')}]`
const upper = (k: string): string => snake(k).replace(/^r#/, '').toUpperCase()

function constants(name: string, doc: string, values: Readonly<Record<string, number | string>>): string[] {
  return [
    `/// ${doc}`,
    `pub mod ${name} {`,
    ...Object.entries(values).map(([k, v]) =>
      typeof v === 'string'
        ? `    pub const ${upper(k)}: &str = ${rustStr(v)};`
        : Number.isInteger(v)
          ? `    pub const ${upper(k)}: i64 = ${v};`
          : `    pub const ${upper(k)}: f64 = ${v};`
    ),
    '}',
    ''
  ]
}

/** The numbers and the grammar's words the service reads, so both sides have one home for them. */
export function emitContract(): string {
  return [
    ...HEADER,
    '#![allow(dead_code)]',
    '',
    '/// COMPUTER_PROTOCOL',
    `pub const COMPUTER_PROTOCOL: i64 = ${COMPUTER_PROTOCOL};`,
    '',
    ...constants('service', 'The process and its frames (§1).', SERVICE),
    ...constants('walk', 'The tree walk (§4.3).', AX_WALK),
    ...constants('text', 'Observation text (§4.1, §4.5).', OBSERVATION_TEXT),
    ...constants('budget', 'The size budget (§4.5).', OBSERVATION_BUDGET),
    ...constants('locks', 'The machine-wide locks (§1, §5.3).', LOCKS),
    ...constants('rpc_error', 'JSON-RPC error codes.', RPC_ERROR),
    '/// The observation grammar\'s words (observation.ts).',
    'pub mod grammar {',
    `    /// Every role word a line may print (ROLE_TAGS' values).`,
    `    pub const ROLE_WORDS: &[&str] = ${strList([...ROLE_WORDS].sort())};`,
    '    /// In the order a line prints them.',
    `    pub const STATE_WORDS: &[&str] = ${strList(STATE_WORDS)};`,
    `    pub const TOGGLE_ROLES: &[&str] = ${strList([...TOGGLE_ROLES].sort())};`,
    `    pub const TYPING_ROLES: &[&str] = ${strList([...TYPING_ROLES].sort())};`,
    '    /// Kept with no name, value, action or state.',
    `    pub const STRUCTURAL_ROLES: &[&str] = ${strList([...STRUCTURAL_ROLES].sort())};`,
    '    /// What every element of a role takes without listing it.',
    '    pub const ROLE_DEFAULTS: &[(&str, &[&str])] = &[',
    ...Object.keys(ROLE_DEFAULTS)
      .sort()
      .map((k) => `        (${rustStr(k)}, ${strList(ROLE_DEFAULTS[k])}),`),
    '    ];',
    `    pub const HEADER_SEPARATOR: &str = ${rustStr(HEADER_SEPARATOR)};`,
    `    pub const HEADER_LOADING: &str = ${rustStr(HEADER_WORDS.loading)};`,
    `    pub const HEADER_THIN: &str = ${rustStr(HEADER_WORDS.thin)};`,
    `    pub const OTHER_WINDOWS_PREFIX: &str = ${rustStr(OTHER_WINDOWS_PREFIX)};`,
    '}',
    '',
    '/// The method names, for the router (COMPUTER_METHODS\' keys).',
    `pub const METHODS: &[&str] = ${strList(Object.keys(COMPUTER_METHODS) as ComputerMethod[])};`,
    ''
  ].join('\n')
}

const here = dirname(fileURLToPath(import.meta.url))
export const RUST_GENERATED_DIR = resolve(here, '..', 'native', 'tc-computer-win', 'src', 'generated')

export function generateRust(): Record<string, string> {
  return {
    'wire.rs': emitWire(),
    'contract.rs': emitContract(),
    'mod.rs': [...HEADER, 'pub mod contract;', 'pub mod wire;', ''].join('\n')
  }
}

/** The names of the committed files that differ from what the generator writes now. */
export function staleFiles(dir = RUST_GENERATED_DIR): string[] {
  const want = generateRust()
  const have = new Set(readdirSync(dir))
  const stale = Object.entries(want)
    .filter(([f, text]) => !have.has(f) || readFileSync(join(dir, f), 'utf8') !== text)
    .map(([f]) => f)
  return [...stale, ...[...have].filter((f) => !(f in want))]
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles()
    if (stale.length) {
      console.error(`stale: ${stale.join(', ')}; run bun scripts/gen-rust-computer.ts`)
      process.exit(1)
    }
  } else {
    mkdirSync(RUST_GENERATED_DIR, { recursive: true })
    for (const [f, text] of Object.entries(generateRust())) writeFileSync(join(RUST_GENERATED_DIR, f), text)
  }
}
