/**
 * The computer-use wire in Rust: src/shared/computer/protocol.ts → the serde
 * types the Windows service decodes and encodes (docs/computer-protocol.md
 * §12, §29). It reads the same JSON Schemas as gen-swift-computer.ts
 * (`jsonSchemas` over COMPUTER_SUBSET), so both services take one contract.
 *
 *   bun scripts/gen-rust-computer.ts           writes native/tc-computer-win/src/generated/
 *   bun scripts/gen-rust-computer.ts --check   exits 1 when the committed files are stale
 *
 * scripts/gen-rust-computer.test.ts runs the check in vitest, so a stale file fails the gate.
 *
 * What it emits: a string enum is an enum with a `#[serde(other)]`
 * `Unrecognized` (an older service tolerates a newer host's value); an object is a struct,
 * an optional field `Option` left out when `None`, a required nullable one
 * `Option` written as `null`; an inline object or enum is named after its
 * parent and field; a discriminated union is an internally tagged enum over
 * its branch structs (the tag field left out of them); a record is a
 * `BTreeMap`; anything else is `serde_json::Value`.
 */
