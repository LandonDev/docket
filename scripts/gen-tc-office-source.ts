/**
 * Writes native/tc-office-win/TcOffice.cs into the server as a string
 * (src/main/server/work/office/com/source.ts): the host compiles the helper
 * from it on Windows (com/helper.ts), so no exe ships. `--check` fails when
 * the two differ (com/helper.test.ts runs it).
 *
 *   bun scripts/gen-tc-office-source.ts [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
export const SOURCE_TS = join(root, 'src/main/server/work/office/com/source.ts')

export function render(cs: string): string {
  return `// Generated by scripts/gen-tc-office-source.ts from native/tc-office-win/TcOffice.cs: edit that file, then run the script.\nexport const TC_OFFICE_CS = ${JSON.stringify(cs)}\n`
}

export const wanted = (): string => render(readFileSync(join(root, 'native/tc-office-win/TcOffice.cs'), 'utf8'))

if (import.meta.main) {
  const now = (() => {
    try {
      return readFileSync(SOURCE_TS, 'utf8')
    } catch {
      return ''
    }
  })()
  if (process.argv.includes('--check')) {
    if (now !== wanted()) {
      console.error('com/source.ts is stale: run bun scripts/gen-tc-office-source.ts')
      process.exit(1)
    }
  } else writeFileSync(SOURCE_TS, wanted())
}
